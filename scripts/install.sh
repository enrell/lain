warn_if_missing_libs() {
  local bin="$1"
  local missing='' deps=''
  if ! command -v ldd >/dev/null 2>&1; then
    return 0
  fi
  missing="$(ldd "$bin" 2>/dev/null | grep 'not found' || true)"
  if [[ -z "$missing" ]]; then
    return 0
  fi
  warn "some shared libraries are missing for $bin:"
  printf '%s\n' "$missing" >&2
  if deps="$(desktop_deps_command)"; then
    info "Install them with: $deps"
  fi
  return 0
}

install_desktop_binary() {
  local bin="$1"
  local kind="${2:-binary}"
  local icon_source="${3:-}"
  local app_dir="${HOME}/.local/share/applications"
  local icon_dir="${HOME}/.local/share/icons/hicolor/256x256/apps"
  local icon_file="${icon_dir}/lain-desktop.png"
  local desktop_file="${app_dir}/lain-desktop.desktop"
  local extract_dir=''
  local tmp="${desktop_file}.tmp.$$"
  if ! mkdir -p -- "$INSTALL_DIR"; then
    warn "could not create $INSTALL_DIR"
    return 1
  fi
  if ! install -m 0755 "$bin" "${INSTALL_DIR}/lain-desktop"; then
    warn "could not install ${INSTALL_DIR}/lain-desktop"
    return 1
  fi
  ok "Installed ${INSTALL_DIR}/lain-desktop"
  check_path
  if [[ "$kind" != 'appimage' ]]; then
    warn_if_missing_libs "${INSTALL_DIR}/lain-desktop"
  fi
  if [[ -z "$icon_source" && "$kind" == 'appimage' ]]; then
    extract_dir="${TMP_DIR}/lain-desktop-icon"
    # Downloads land non-executable (curl + umask); the image must run
    # to unpack its own icon, so mark it executable first.
    if mkdir -p -- "$extract_dir" &&
       chmod +x -- "$bin" 2>/dev/null &&
       (cd "$extract_dir" && "$bin" --appimage-extract \
         'usr/share/icons/hicolor/256x256/apps/lain-desktop.png' >/dev/null 2>&1) &&
       [[ -f "${extract_dir}/squashfs-root/usr/share/icons/hicolor/256x256/apps/lain-desktop.png" ]]; then
      icon_source="${extract_dir}/squashfs-root/usr/share/icons/hicolor/256x256/apps/lain-desktop.png"
    fi
  fi
  if ! mkdir -p -- "$app_dir" "$icon_dir"; then
    warn "could not create desktop integration directories"
    return 1
  fi
  if [[ -n "$icon_source" && -f "$icon_source" ]]; then
    if ! install -m 0644 "$icon_source" "$icon_file"; then
      warn "could not install $icon_file"
      return 1
    fi
    ok "Installed $icon_file"
  else
    warn "desktop icon was not found in the installation payload"
  fi
  {
    printf '[Desktop Entry]\n'
    printf '# %s -- do not edit; re-run the installer to regenerate.\n' "$GENERATED_MARKER"
    printf 'Type=Application\n'
    printf 'Name=Lain\n'
    printf 'GenericName=Media Client\n'
    printf 'Comment=lain media server desktop client\n'
    printf 'Exec=lain-desktop\n'
    printf 'Icon=lain-desktop\n'
    printf 'Terminal=false\n'
    printf 'Categories=AudioVideo;Player;\n'
    printf 'Keywords=media;player;lain;\n'
    printf 'StartupWMClass=lain-desktop\n'
  } > "$tmp" || {
    rm -f -- "$tmp" || true
    warn "could not write $desktop_file"
    return 1
  }
  if ! mv -f -- "$tmp" "$desktop_file"; then
    rm -f -- "$tmp" || true
    warn "could not write $desktop_file"
    return 1
  fi
  ok "Wrote $desktop_file"
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$app_dir" || warn "update-desktop-database failed (harmless)"
  else
    info "update-desktop-database not found; the application menu may need a moment to refresh"
  fi
  add_note "desktop client: ${INSTALL_DIR}/lain-desktop"
  add_next "Launch the client with: lain-desktop (or from the application menu)"
  if [[ "$kind" == 'appimage' ]]; then
    add_next "No FUSE? Run it as: lain-desktop --appimage-extract-and-run"
  fi
  return 0
}

build_desktop_from_source() {
  local deps='' src='' build='' bin=''
  local tool=''
  step "Building lain-desktop from source"
  if deps="$(desktop_deps_command)"; then
    info "Dependencies: $deps"
    if confirm "Install distro dependencies now?" y; then
      run_deps_command "$deps" || warn "dependency install failed (continuing; the build may fail)"
    else
      warn "skipping dependency install; the build may fail"
    fi
  else
    warn "unrecognized distribution; install Qt6 (base + declarative), libmpv, cmake, ninja and git manually"
    warn "see ${GITHUB}/${DESKTOP_REPO}"
  fi
  for tool in git cmake ninja; do
    if ! command -v "$tool" >/dev/null 2>&1; then
      warn "required tool not found: $tool"
      return 1
    fi
  done
  ensure_tmp
  src="${TMP_DIR}/lain-desktop-src"
  info "Cloning ${GITHUB}/${DESKTOP_REPO}.git"
  if ! git clone --depth 1 "${GITHUB}/${DESKTOP_REPO}.git" "$src"; then
    warn "git clone failed"
    return 1
  fi
  build="${src}/build"
  if ! cmake -S "$src" -B "$build" -G Ninja -DCMAKE_BUILD_TYPE=Release; then
    warn "cmake configure failed"
    return 1
  fi
  if ! cmake --build "$build"; then
    warn "cmake build failed"
    return 1
  fi
  bin="$(find "$build" -maxdepth 3 -type f -perm -u+x \( -name 'lain-desktop' -o -name 'lain' \) -print -quit)"
  if [[ -z "$bin" ]]; then
    warn "built binary not found under $build"
    return 1
  fi
  if ! install_desktop_binary "$bin" binary "${src}/packaging/lain-desktop.png"; then
    return 1
  fi
  return 0
}

install_desktop() {
  local arch='' ver='' asset='' url='' image=''
  local rc=0
  ensure_tmp
  if ! arch="$(detect_arch)"; then
    warn "unsupported CPU architecture: $(uname -m) (desktop builds exist for x86_64)"
    return 1
  fi
  step "Desktop client (${VERSION}, ${arch})"
  if [[ "$arch" != 'x86_64' ]]; then
    warn "no prebuilt desktop AppImage is published for ${arch}; a source build is needed"
    if confirm "Build lain-desktop from source now?" y; then
      build_desktop_from_source || return 1
      return 0
    fi
    warn "skipped the desktop install"
    return 1
  fi
  if ver="$(asset_version_for "$DESKTOP_REPO")"; then
    asset="lain-desktop_${ver}_linux_x86_64.AppImage"
    url="$(release_url "$DESKTOP_REPO" "$asset")"
    image="${TMP_DIR}/${asset}"
    info "Downloading ${url}"
    fetch_release_asset "$url" "$image" || rc=$?
  else
    rc=1
  fi
  if [[ "$rc" -eq 0 ]]; then
    install_desktop_binary "$image" appimage || return 1
    return 0
  fi
  if [[ "$rc" -eq 2 ]]; then
    warn "the downloaded AppImage failed checksum verification; not installing it"
  else
    warn "no prebuilt desktop AppImage is available for this version/arch"
    if [[ -n "$url" ]]; then
      info "Requested: $url"
    fi
    warn "the desktop app can also be built from source against system Qt6 + libmpv"
  fi
  if confirm "Build lain-desktop from source now?" y; then
    build_desktop_from_source || return 1
    return 0
  fi
  warn "skipped the desktop install"
  return 1
}

