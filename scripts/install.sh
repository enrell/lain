install_server_binary() {
  local arch='' ver='' asset='' url='' archive='' extract='' bin=''
  local rc=0
  ensure_tmp
  if ! arch="$(server_arch)"; then
    warn "unsupported CPU architecture: $(uname -m) (server builds exist for x86_64 and aarch64)"
    return 1
  fi
  if ! ver="$(asset_version_for "$SERVER_REPO")"; then
    warn "could not determine the latest server release tag (network problem?)"
    warn "pin a release explicitly, e.g. --version v0.1.0"
    return 1
  fi
  asset="lain_${ver}_linux_${arch}.tar.gz"
  url="$(release_url "$SERVER_REPO" "$asset")"
  archive="${TMP_DIR}/${asset}"
  extract="${TMP_DIR}/server"
  if ! mkdir -p -- "$extract"; then
    warn "could not create $extract"
    return 1
  fi
  step "Server binary ${VERSION} (${arch})"
  info "Downloading ${url}"
  fetch_release_asset "$url" "$archive" || rc=$?
  if [[ "$rc" -eq 1 ]]; then
    warn "release asset not found: $url"
    warn "see available releases: ${GITHUB}/${SERVER_REPO}/releases"
    return 1
  fi
  if [[ "$rc" -ne 0 ]]; then
    warn "checksum verification failed for $url"
    return 1
  fi
  if ! tar -xzf "$archive" -C "$extract"; then
    warn "could not extract $archive"
    return 1
  fi
  bin="$(find "$extract" -maxdepth 2 -type f -name 'lain' -print -quit)"
  if [[ -z "$bin" ]]; then
    warn "'lain' binary not found inside $asset"
    return 1
  fi
  if ! mkdir -p -- "$INSTALL_DIR"; then
    warn "could not create $INSTALL_DIR"
    return 1
  fi
  if ! install -m 0755 "$bin" "${INSTALL_DIR}/lain"; then
    warn "could not install ${INSTALL_DIR}/lain"
    return 1
  fi
  ok "Installed ${INSTALL_DIR}/lain"
  check_path
  add_note "server CLI: ${INSTALL_DIR}/lain"
  add_next "Run: \"${INSTALL_DIR}/lain\" serve --data-dir \"${DATA_DIR}\" --port ${PORT}"
  add_next "Open http://127.0.0.1:${PORT}/ for first-run setup"
  return 0
}

print_systemd_manual() {
  info "Control it manually with:"
  info "  systemctl --user daemon-reload"
  info "  systemctl --user enable --now lain.service"
  info "  systemctl --user status lain.service"
}

enable_linger_if_wanted() {
  local user="${USER:-$(id -un)}"
  local linger=''
  linger="$(loginctl show-user "$user" -p Linger --value 2>/dev/null || true)"
  if [[ "$linger" == 'yes' ]]; then
    return 0
  fi
  info "Tip: a user service stops when you log out unless lingering is enabled."
  if confirm "Run 'loginctl enable-linger' so lain keeps running after logout?" n; then
    if loginctl enable-linger "$user"; then
      ok "enabled lingering for $user"
    else
      warn "loginctl enable-linger failed; run it manually: loginctl enable-linger $user"
    fi
  else
    info "Keep it running after logout later with: loginctl enable-linger $user"
  fi
  return 0
}

install_systemd_unit() {
  local unit_dir="${HOME}/.config/systemd/user"
  local unit_file="${unit_dir}/lain.service"
  local tmp="${unit_file}.tmp.$$"
  local exe='' data=''
  if ! command -v systemctl >/dev/null 2>&1; then
    warn "systemctl not found; skipping the systemd user service"
    return 1
  fi
  if ! confirm "Create and start the lain systemd user service?" y; then
    info "Skipped; create it later by re-running: ${SCRIPT_PATH:-install.sh} --server --server-mode daemon"
    return 0
  fi
  exe="$(systemd_quote_arg "${INSTALL_DIR}/lain")"
  data="$(systemd_quote_arg "$DATA_DIR")"
  if ! mkdir -p -- "$unit_dir"; then
    warn "could not create $unit_dir"
    return 1
  fi
  {
    printf '# %s -- do not edit; re-run the installer to regenerate.\n' "$GENERATED_MARKER"
    printf '[Unit]\n'
    printf 'Description=lain media server\n'
    printf 'Documentation=%s/%s\n' "$GITHUB" "$SERVER_REPO"
    printf '\n[Service]\n'
    printf 'ExecStart=%s serve --data-dir %s --port %s\n' "$exe" "$data" "$PORT"
    printf 'Restart=on-failure\n'
    printf 'RestartSec=3\n'
    printf '\n[Install]\n'
    printf 'WantedBy=default.target\n'
  } > "$tmp" || {
    rm -f -- "$tmp" || true
    warn "could not write $unit_file"
    return 1
  }
  if ! mv -f -- "$tmp" "$unit_file"; then
    rm -f -- "$tmp" || true
    warn "could not write $unit_file"
    return 1
  fi
  ok "Wrote $unit_file"
  if ! systemctl --user daemon-reload; then
    warn "systemctl --user daemon-reload failed"
    print_systemd_manual
    return 1
  fi
  if systemctl --user enable --now lain.service; then
    ok "systemd user service enabled and started"
    add_note "user service: $unit_file"
    add_next "systemctl --user status lain.service"
    add_next "journalctl --user -u lain.service -f"
  else
    warn "could not enable/start the user service"
    print_systemd_manual
    return 1
  fi
  enable_linger_if_wanted
  return 0
}

install_server_daemon() {
  if ! install_server_binary; then
    return 1
  fi
  if ! install_systemd_unit; then
    warn "the server binary is installed but the user service is not active"
    return 1
  fi
  return 0
}

