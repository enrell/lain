# --- Interaction helpers ---------------------------------------------------

trim() {
  local s="$1"
  s="${s#"${s%%[![:space:]]*}"}"
  s="${s%"${s##*[![:space:]]}"}"
  printf '%s' "$s"
}

# prompt VAR "label" [default] -- sets VAR; silent when non-interactive.
prompt() {
  local var_name="$1"
  local label="$2"
  local default_value="${3:-}"
  local answer=''
  if [[ "$ASSUME_YES" -eq 1 || "$INTERACTIVE" -eq 0 ]]; then
    printf -v "$var_name" '%s' "$default_value"
    return 0
  fi
  if [[ -n "$default_value" ]]; then
    printf '%s [%s]: ' "$label" "$default_value" >&2
  else
    printf '%s: ' "$label" >&2
  fi
  if [[ -r /dev/tty ]]; then
    IFS= read -r answer < /dev/tty || answer=''
  else
    IFS= read -r answer || answer=''
  fi
  if [[ -z "$answer" ]]; then
    answer="$default_value"
  fi
  printf -v "$var_name" '%s' "$answer"
}

# Readline filename completion, with editable default and literal paths.
# Output names must not start with _path_. No eval: paths are data.
prompt_path() {
  local _path_var="$1" _path_label="$2" _path_default="${3:-}" _path_value=''
  if [[ "$ASSUME_YES" -eq 1 || "$INTERACTIVE" -eq 0 ]]; then
    printf -v "$_path_var" '%s' "$_path_default"
    return 0
  fi
  printf '%s (Tab completes paths; clear to skip): ' "$_path_label" >&2
  # Readline quotes completed names (e.g. Films\ Archive). Let read consume
  # those escapes. Quote the initial text too, so defaults round-trip.
  _path_default="${_path_default//\\/\\\\}"
  # shellcheck disable=SC2162 # intentional: undo Readline's filename quoting
  IFS= read -e -i "$_path_default" _path_value < /dev/tty || return 1
  printf -v "$_path_var" '%s' "$_path_value"
}

# confirm "question" [y|n] -- default is n.
confirm() {
  local question="$1"
  local default_answer="${2:-n}"
  local answer=''
  local suffix='[y/N]'
  if [[ "$default_answer" == 'y' ]]; then
    suffix='[Y/n]'
  fi
  if [[ "$ASSUME_YES" -eq 1 || "$INTERACTIVE" -eq 0 ]]; then
    if [[ "$default_answer" == 'y' ]]; then
      return 0
    fi
    return 1
  fi
  printf '%s %s ' "$question" "$suffix" >&2
  if [[ -r /dev/tty ]]; then
    IFS= read -r answer < /dev/tty || answer=''
  else
    IFS= read -r answer || answer=''
  fi
  case "$answer" in
    [yY]*) return 0 ;;
    [nN]*) return 1 ;;
    *)
      if [[ "$default_answer" == 'y' ]]; then
        return 0
      fi
      return 1
      ;;
  esac
}

# --- Path helpers ----------------------------------------------------------

abspath() {
  local p="$1"
  if [[ -z "$p" ]]; then
    die "empty path given"
  fi
  case "$p" in
    '~') p="$HOME" ;;
    '~'/*) p="${HOME}/${p#~/}" ;;
    '~'*) die "'~user' paths are not supported: $p" ;;
  esac
  case "$p" in
    /*) ;;
    *) p="${PWD}/${p}" ;;
  esac
  if command -v realpath >/dev/null 2>&1; then
    realpath -m -- "$p" || printf '%s' "$p"
  else
    printf '%s' "$p"
  fi
}

normalize_paths() {
  INSTALL_DIR="$(abspath "$INSTALL_DIR")"
  DATA_DIR="$(abspath "$DATA_DIR")"
  COMPOSE_DIR="$(abspath "$COMPOSE_DIR")"
  if ((${#MEDIA_DIRS[@]} > 0)); then
    local -a normalized=()
    local m=''
    for m in "${MEDIA_DIRS[@]}"; do
      normalized+=("$(abspath "$m")")
    done
    MEDIA_DIRS=("${normalized[@]}")
  fi
}

ensure_tmp() {
  if [[ -z "$TMP_DIR" ]]; then
    TMP_DIR="$(mktemp -d "${TMP_BASE}/lain-install.XXXXXX")" || die "could not create a temp directory under ${TMP_BASE}"
  fi
}

cleanup() {
  if [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]]; then
    case "$TMP_DIR" in
      "${TMP_BASE}"/lain-install.*)
        rm -rf -- "$TMP_DIR" || true
        ;;
    esac
  fi
}

# --- Validation helpers ----------------------------------------------------

normalize_tag() {
  local v="$1"
  if [[ "$v" == 'latest' || -z "$v" ]]; then
    printf 'latest'
    return 0
  fi
  if [[ "$v" =~ ^v?[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
    printf 'v%s' "${v#v}"
    return 0
  fi
  return 1
}

validate_version() {
  local tag=''
  if ! tag="$(normalize_tag "$VERSION")"; then
    die "invalid version '$VERSION' (expected latest, v0.1.0 or 0.1.0)"
  fi
  VERSION="$tag"
}

validate_port() {
  if [[ ! "$PORT" =~ ^[0-9]{1,5}$ ]]; then
    die "invalid port '$PORT' (expected an integer between 1 and 65535)"
  fi
  if ((10#$PORT < 1 || 10#$PORT > 65535)); then
    die "invalid port '$PORT' (expected an integer between 1 and 65535)"
  fi
}

prompt_port() {
  local value=''
  while true; do
    prompt value 'HTTP port' "$PORT"
    if [[ "$value" =~ ^[0-9]{1,5}$ ]] && ((10#$value >= 1 && 10#$value <= 65535)); then
      PORT="$value"
      return 0
    fi
    warn "port must be an integer between 1 and 65535"
    if [[ "$INTERACTIVE" -eq 0 ]]; then
      die "invalid port '$value'"
    fi
  done
}

# --- Platform helpers ------------------------------------------------------

detect_arch() {
  case "$(uname -m)" in
    x86_64|amd64) printf 'x86_64' ;;
    aarch64|arm64) printf 'aarch64' ;;
    *) return 1 ;;
  esac
}

server_arch() {
  local arch=''
  if ! arch="$(detect_arch)"; then
    return 1
  fi
  case "$arch" in
    x86_64) printf 'amd64' ;;
    aarch64) printf 'arm64' ;;
    *) return 1 ;;
  esac
}

detect_distro() {
  local id='' like=''
  if [[ -r /etc/os-release ]]; then
    id="$(awk -F= '$1 == "ID" {gsub(/"/, "", $2); print $2; exit}' /etc/os-release 2>/dev/null || true)"
    like="$(awk -F= '$1 == "ID_LIKE" {gsub(/"/, "", $2); print $2; exit}' /etc/os-release 2>/dev/null || true)"
  fi
  case "$id" in
    arch|manjaro|endeavouros|garuda) printf 'arch' ;;
    debian|ubuntu|linuxmint|pop|zorin|kali) printf 'debian' ;;
    fedora|rhel|centos|rocky|almalinux) printf 'fedora' ;;
    *)
      case " $like " in
        *' arch '*) printf 'arch' ;;
        *' debian '*|*' ubuntu '*) printf 'debian' ;;
        *' fedora '*|*' rhel '*) printf 'fedora' ;;
        *) printf 'unknown' ;;
      esac
      ;;
  esac
}

desktop_deps_command() {
  case "$(detect_distro)" in
    arch)
      printf '%s' 'sudo pacman -S --needed base-devel cmake ninja qt6-base qt6-declarative mpv ffmpeg'
      ;;
    debian)
      printf '%s' 'sudo apt install build-essential cmake ninja-build qt6-base-dev qt6-declarative-dev qml6-module-qtquick qml6-module-qtquick-controls qml6-module-qtquick-layouts libmpv-dev ffmpeg'
      ;;
    fedora)
      printf '%s' 'sudo dnf install cmake ninja-build qt6-qtbase-devel qt6-qtdeclarative-devel mpv-libs-devel ffmpeg'
      ;;
    *)
      return 1
      ;;
  esac
}

run_deps_command() {
  local cmd="$1"
  local -a argv=()
  if [[ -z "$cmd" ]]; then
    return 1
  fi
  read -r -a argv <<< "$cmd"
  if ((${#argv[@]} == 0)); then
    return 1
  fi
  if [[ "$EUID" -eq 0 ]]; then
    if [[ "${argv[0]}" == 'sudo' ]]; then
      argv=("${argv[@]:1}")
    fi
  else
    if [[ "${argv[0]}" != 'sudo' ]]; then
      argv=('sudo' "${argv[@]}")
    fi
    if [[ "$INTERACTIVE" -eq 0 ]]; then
      argv=("${argv[0]}" '-n' "${argv[@]:1}")
    fi
  fi
  if [[ "$ASSUME_YES" -eq 1 || "$INTERACTIVE" -eq 0 ]]; then
    case " ${argv[*]} " in
      *' apt '*) argv+=('-y') ;;
      *' pacman '*) argv+=('--noconfirm') ;;
      *' dnf '*) argv+=('-y') ;;
    esac
  fi
  "${argv[@]}"
}

systemd_home_path() {
  local p="$1"
  if [[ "$p" == "$HOME" ]]; then
    printf '%%h'
  elif [[ "$p" == "$HOME"/* ]]; then
    printf '%%h/%s' "${p#"$HOME"/}"
  else
    printf '%s' "$p"
  fi
}

systemd_quote_arg() {
  local s=''
  s="$(systemd_home_path "$1")"
  if [[ "$s" == *[[:space:]]* ]]; then
    printf '"%s"' "${s//\"/\\\"}"
  else
    printf '%s' "$s"
  fi
}

# --- Release helpers -------------------------------------------------------

latest_tag() {
  local repo="$1"
  local effective=''
  effective="$(curl -fsSIL --proto '=https' --connect-timeout 15 -o /dev/null -w '%{url_effective}' "${GITHUB}/${repo}/releases/latest" 2>/dev/null || true)"
  case "$effective" in
    */releases/tag/*) printf '%s' "${effective##*/}" ;;
    *) return 1 ;;
  esac
}

# Numeric version used in asset names (no leading v), resolving "latest".
asset_version_for() {
  local repo="$1"
  local tag=''
  if [[ "$VERSION" == 'latest' ]]; then
    if ! tag="$(latest_tag "$repo")"; then
      return 1
    fi
  else
    tag="$VERSION"
  fi
  printf '%s' "${tag#v}"
}

release_url() {
  local repo="$1"
  local asset="$2"
  if [[ "$VERSION" == 'latest' ]]; then
    printf '%s/%s/releases/latest/download/%s' "$GITHUB" "$repo" "$asset"
  else
    printf '%s/%s/releases/download/%s/%s' "$GITHUB" "$repo" "$VERSION" "$asset"
  fi
}

download() {
  local url="$1"
  local dest="$2"
  curl -fsSL --proto '=https' --retry 3 --connect-timeout 15 --max-time 900 -o "$dest" "$url"
}

verify_checksum() {
  local file="$1"
  local sidecar="$2"
  local expected='' actual=''
  expected="$(awk 'NR == 1 {print $1}' "$sidecar")"
  if [[ ! "$expected" =~ ^[0-9a-fA-F]{64}$ ]]; then
    warn "unrecognized checksum file: $sidecar"
    return 1
  fi
  actual="$(sha256sum -- "$file" | awk '{print $1}')"
  if [[ "${expected,,}" != "${actual,,}" ]]; then
    warn "checksum mismatch for $(basename -- "$file")"
    return 1
  fi
  ok "checksum verified: $(basename -- "$file")"
  return 0
}

# fetch_release_asset URL DEST
#   0 = downloaded (checksum verified when a sidecar exists)
#   1 = download failed (missing asset / network)
#   2 = checksum verification failed
fetch_release_asset() {
  local url="$1"
  local dest="$2"
  local sidecar="${dest}.sha256"
  if ! download "$url" "$dest"; then
    return 1
  fi
  if download "${url}.sha256" "$sidecar" 2>/dev/null; then
    if verify_checksum "$dest" "$sidecar"; then
      return 0
    fi
    return 2
  fi
  warn "no .sha256 sidecar for $(basename -- "$url"); skipping checksum verification"
  return 0
}

# --- Compose helpers -------------------------------------------------------

detect_compose() {
  COMPOSE=()
  if command -v docker >/dev/null 2>&1; then
    if docker compose version >/dev/null 2>&1; then
      COMPOSE=(docker compose)
      return 0
    fi
  fi
  if command -v docker-compose >/dev/null 2>&1; then
    COMPOSE=(docker-compose)
    return 0
  fi
  return 1
}

docker_ready() {
  if ((${#COMPOSE[@]} == 0)); then
    return 1
  fi
  docker info >/dev/null 2>&1
}

compose_run() {
  if ((${#COMPOSE[@]} == 0)); then
    return 1
  fi
  (cd "$COMPOSE_DIR" && "${COMPOSE[@]}" "$@")
}

yaml_quote() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  printf '"%s"' "$s"
}

sanitize_name() {
  local base='' name=''
  base="$(basename -- "$1")"
  name="$(printf '%s' "$base" | tr '[:upper:]' '[:lower:]' | sed -e 's/[^a-z0-9._-]/-/g' -e 's/--*/-/g' -e 's/^[-._]*//' -e 's/[-._]*$//')"
  if [[ -z "$name" || "$name" == '.' || "$name" == '..' ]]; then
    name='media'
  fi
  printf '%s' "$name"
}

# Short-syntax bind mounts cannot express a host path containing ':' or a
# newline; fail early with a clear message instead of writing broken YAML.
check_docker_path() {
  local path="$1"
  local label="$2"
  if [[ "$path" == *$'\n'* ]]; then
    warn "$label contains a newline and cannot be used as a Docker bind mount: $path"
    return 1
  fi
  if [[ "$path" == *:* ]]; then
    warn "$label contains ':' and cannot be used as a Docker bind mount: $path"
    return 1
  fi
  return 0
}

write_compose_file() {
  local image="$1"
  shift
  local compose_file="${COMPOSE_DIR}/docker-compose.yml"
  local tmp="${compose_file}.tmp.$$"
  local backup=''
  local volume=''
  if [[ -f "$compose_file" ]]; then
    backup="${compose_file}.bak.$(date +%Y%m%d%H%M%S).$$"
    if cp -a -- "$compose_file" "$backup"; then
      warn "existing compose file backed up to $backup"
    else
      warn "could not back up $compose_file"
      return 1
    fi
  fi
  {
    printf '# %s -- yours to audit and edit.\n' "$GENERATED_MARKER"
    printf '# Apply edits: docker compose up -d\n'
    printf '# Volume syntax: HOST_DIRECTORY:CONTAINER_DIRECTORY:ro\n'
    printf '# Add media mounts below, then register their CONTAINER paths in Lain.\n'
    printf '# Example: /srv/media/films:/media/films:ro\n'
    printf '# Re-running the installer reuses this file by default.\n'
    printf 'services:\n'
    printf '  lain:\n'
    printf '    image: %s\n' "$image"
    printf '    container_name: lain\n'
    printf '    restart: unless-stopped\n'
    # shellcheck disable=SC2016  # literal ${UID}:${GID}; values come from .env
    printf '    user: "${UID}:${GID}"\n'
    printf '    ports:\n'
    printf '      - "%s:%s"\n' "$PORT" "$CONTAINER_PORT"
    printf '    volumes:\n'
    printf '      # Persistent database and cache (read/write).\n'
    printf '      - %s\n' "$(yaml_quote "${DATA_DIR}:${CONTAINER_DATA_DIR}")"
    printf '      # Media stays on the host; mount read-only.\n'
    for volume in "$@"; do
      printf '      - %s\n' "$(yaml_quote "$volume")"
    done
    printf '    environment:\n'
    printf '      GOMEMLIMIT: 256MiB\n'
    printf '      GOGC: "100"\n'
    printf '    mem_limit: 384m\n'
    printf '    healthcheck:\n'
    printf '      test: ["CMD", "wget", "-qO-", "http://127.0.0.1:%s/health"]\n' "$CONTAINER_PORT"
    printf '      interval: 30s\n'
    printf '      timeout: 5s\n'
    printf '      start_period: 5s\n'
    printf '      retries: 3\n'
  } > "$tmp" || {
    rm -f -- "$tmp" || true
    return 1
  }
  if ! mv -f -- "$tmp" "$compose_file"; then
    rm -f -- "$tmp" || true
    return 1
  fi
  ok "Wrote $compose_file"
  return 0
}

write_env_file() {
  local env_file="${COMPOSE_DIR}/.env"
  local tmp="${env_file}.tmp.$$"
  local backup=''
  if [[ -f "$env_file" ]]; then
    backup="${env_file}.bak.$(date +%Y%m%d%H%M%S).$$"
    if cp -a -- "$env_file" "$backup"; then
      warn "existing .env backed up to $backup"
    else
      warn "could not back up $env_file"
      return 1
    fi
  fi
  {
    printf '# %s -- host UID/GID; edit to match the media owner.\n' "$GENERATED_MARKER"
    printf 'UID=%s\n' "$(id -u)"
    printf 'GID=%s\n' "$(id -g)"
  } > "$tmp" || {
    rm -f -- "$tmp" || true
    return 1
  }
  if ! mv -f -- "$tmp" "$env_file"; then
    rm -f -- "$tmp" || true
    return 1
  fi
  ok "Wrote $env_file (UID/GID for the container user)"
  return 0
}

print_compose_manual() {
  info "Start it manually with:"
  info "  cd ${COMPOSE_DIR} && docker compose pull && docker compose up -d"
  info "  docker compose logs -f"
}

