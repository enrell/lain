parse_args() {
  while (($# > 0)); do
    case "$1" in
      --server) SERVER=1; shift ;;
      --desktop) DESKTOP=1; shift ;;
      --both) SERVER=1; DESKTOP=1; shift ;;
      --no-server) SERVER=0; shift ;;
      --no-desktop) DESKTOP=0; shift ;;
      --server-mode)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--server-mode needs a value (docker, binary or daemon)"
        fi
        MODE="$2"
        shift 2
        ;;
      --server-mode=*)
        MODE="${1#*=}"
        if [[ -z "$MODE" ]]; then
          die "--server-mode needs a value (docker, binary or daemon)"
        fi
        shift
        ;;
      --media)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--media needs a non-empty path"
        fi
        MEDIA_DIRS+=("$2")
        MEDIA_GIVEN=1
        shift 2
        ;;
      --media=*)
        if [[ -z "${1#*=}" ]]; then
          die "--media needs a non-empty path"
        fi
        MEDIA_DIRS+=("${1#*=}")
        MEDIA_GIVEN=1
        shift
        ;;
      --data)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--data needs a non-empty path"
        fi
        DATA_DIR="$2"
        DATA_SET=1
        shift 2
        ;;
      --data=*)
        if [[ -z "${1#*=}" ]]; then
          die "--data needs a non-empty path"
        fi
        DATA_DIR="${1#*=}"
        DATA_SET=1
        shift
        ;;
      --port)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--port needs a value"
        fi
        PORT="$2"
        PORT_SET=1
        shift 2
        ;;
      --port=*)
        if [[ -z "${1#*=}" ]]; then
          die "--port needs a value"
        fi
        PORT="${1#*=}"
        PORT_SET=1
        shift
        ;;
      --install-dir)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--install-dir needs a non-empty path"
        fi
        INSTALL_DIR="$2"
        INSTALL_SET=1
        shift 2
        ;;
      --install-dir=*)
        if [[ -z "${1#*=}" ]]; then
          die "--install-dir needs a non-empty path"
        fi
        INSTALL_DIR="${1#*=}"
        INSTALL_SET=1
        shift
        ;;
      --compose-dir)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--compose-dir needs a non-empty path"
        fi
        COMPOSE_DIR="$2"
        COMPOSE_SET=1
        shift 2
        ;;
      --compose-dir=*)
        if [[ -z "${1#*=}" ]]; then
          die "--compose-dir needs a non-empty path"
        fi
        COMPOSE_DIR="${1#*=}"
        COMPOSE_SET=1
        shift
        ;;
      --version)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--version needs a value"
        fi
        VERSION="$2"
        VERSION_SET=1
        shift 2
        ;;
      --version=*)
        if [[ -z "${1#*=}" ]]; then
          die "--version needs a value"
        fi
        VERSION="${1#*=}"
        VERSION_SET=1
        shift
        ;;
      -y|--yes) ASSUME_YES=1; shift ;;
      --uninstall-level)
        if (($# < 2)) || [[ -z "$2" ]]; then
          die "--uninstall-level needs a value (stop, standard or full)"
        fi
        UNINSTALL=1
        set_uninstall_level "$2"
        shift 2
        ;;
      --uninstall-level=*)
        if [[ -z "${1#*=}" ]]; then
          die "--uninstall-level needs a value (stop, standard or full)"
        fi
        UNINSTALL=1
        set_uninstall_level "${1#*=}"
        shift
        ;;
      --uninstall) UNINSTALL=1; shift ;;
      --uninstall=*)
        if [[ -z "${1#*=}" ]]; then
          die "--uninstall needs a value (stop, standard or full)"
        fi
        UNINSTALL=1
        set_uninstall_level "${1#*=}"
        shift
        ;;
      --purge-data) PURGE_DATA=1; shift ;;
      --remove-image) REMOVE_IMAGE=1; shift ;;
      -h|--help) usage; exit 0 ;;
      --) shift; break ;;
      *) die "unknown option: $1 (try --help)" ;;
    esac
  done
  if (($# > 0)); then
    die "unexpected argument(s): $*"
  fi
}

detect_interactive() {
  INTERACTIVE=0
  if [[ "$ASSUME_YES" -eq 0 ]]; then
    # Probe for a usable controlling terminal without leaking the probe's
    # stderr redirect into the shell (a bare "exec 3<>/dev/tty 2>/dev/null"
    # would permanently redirect this script's stderr to /dev/null).
    if : 2>/dev/null < /dev/tty; then
      INTERACTIVE=1
    fi
  fi
  if [[ "$ASSUME_YES" -eq 0 && "$INTERACTIVE" -eq 0 ]]; then
    warn "no terminal available; using defaults (same as --yes)"
    ASSUME_YES=1
  fi
}

# --- Main ------------------------------------------------------------------

main() {
  parse_args "$@"
  # ${#BASH_SOURCE[@]} is safe under set -u; indexing element 0 of an
  # empty BASH_SOURCE (piped via stdin) is not.
  local self="$0"
  if ((${#BASH_SOURCE[@]} > 0)); then
    self="${BASH_SOURCE[0]}"
  fi
  if [[ "$self" == /* ]]; then
    SCRIPT_PATH="$self"
  elif [[ -n "$self" && -f "$self" ]]; then
    SCRIPT_PATH="${PWD}/${self}"
  else
    SCRIPT_PATH='install.sh'
  fi
  trap cleanup EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM
  detect_interactive
  detect_compose || true
  normalize_paths
  if [[ "$UNINSTALL" -eq 1 ]]; then
    uninstall_all
    exit 0
  fi
  if [[ -z "$SERVER" && -z "$DESKTOP" ]]; then
    if [[ "$INTERACTIVE" -eq 1 ]]; then
      choose_components
      if [[ "$UNINSTALL" -eq 1 ]]; then
        uninstall_all
        exit 0
      fi
    else
      SERVER=1
      DESKTOP=0
    fi
  fi
  local want_server="${SERVER:-0}"
  local want_desktop="${DESKTOP:-0}"
  if [[ "$want_server" -eq 0 && "$want_desktop" -eq 0 ]]; then
    die "nothing selected (use --server, --desktop or --both)"
  fi
  if [[ "$want_server" -eq 1 && -z "$MODE" ]]; then
    if [[ "$INTERACTIVE" -eq 1 ]]; then
      choose_server_mode
    else
      MODE='docker'
    fi
  fi
  if [[ "$want_server" -eq 1 ]]; then
    case "$MODE" in
      docker|binary|daemon) ;;
      *) die "invalid server mode '$MODE' (docker, binary or daemon)" ;;
    esac
  fi
  validate_version
  validate_port
  if [[ "$want_server" -eq 1 ]]; then
    if [[ "$MODE" == 'docker' ]]; then
      configure_docker
    else
      configure_server_binary
    fi
  fi
  if [[ "$want_desktop" -eq 1 ]]; then
    configure_desktop
  fi
  validate_version
  validate_port
  normalize_paths
  if [[ "$want_server" -eq 1 && "$MEDIA_GIVEN" -eq 1 && "$MODE" != 'docker' ]]; then
    warn "--media only applies to Docker mode; the binary reads local paths directly"
  fi
  local rc=0
  if [[ "$want_server" -eq 1 ]]; then
    case "$MODE" in
      docker)
        if ! install_server_docker; then
          FAILURES+=('server (Docker)')
          rc=1
        fi
        ;;
      binary)
        if ! install_server_binary; then
          FAILURES+=('server (binary)')
          rc=1
        fi
        ;;
      daemon)
        if ! install_server_daemon; then
          FAILURES+=('server (daemon)')
          rc=1
        fi
        ;;
    esac
  fi
  if [[ "$want_desktop" -eq 1 ]]; then
    if ! install_desktop; then
      FAILURES+=('desktop client')
      rc=1
    fi
  fi
  print_summary
  if [[ "$rc" -ne 0 ]]; then
    exit 1
  fi
}

if ((${#BASH_SOURCE[@]} == 0)); then
  main "$@" # piped via stdin (curl ... | bash): no file to source
elif [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
